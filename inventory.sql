SELECT
    product_id,
    product_name,
    quantity,
    unit,
    expiry_date,
    CASE
        WHEN expiry_date < TRUNC(SYSDATE)
            THEN 'EXPIRED'
        WHEN expiry_date <= TRUNC(SYSDATE) + 7
            THEN 'EXPIRING SOON'
        ELSE 'NORMAL'
    END AS product_status
FROM household_products
ORDER BY expiry_date NULLS LAST;

SELECT
    product_id,
    product_name,
    quantity,
    unit,
    min_stock
FROM household_products
WHERE quantity <= min_stock
ORDER BY product_name;

CREATE TABLE shopping_list (
    item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR2(100) NOT NULL,
    quantity_needed NUMBER(10,2) NOT NULL,
    unit VARCHAR2(20),
    is_purchased CHAR(1) DEFAULT 'N' NOT NULL,
    generated_on DATE DEFAULT SYSDATE,
    CONSTRAINT chk_shopping_quantity
        CHECK (quantity_needed > 0),
    CONSTRAINT chk_purchased
        CHECK (is_purchased IN ('Y', 'N'))
);

CREATE OR REPLACE PROCEDURE generate_shopping_list
AS
BEGIN
    INSERT INTO shopping_list (
        product_name,
        quantity_needed,
        unit
    )
    SELECT
        p.product_name,
        GREATEST(p.min_stock - p.quantity, 0.01),
        p.unit
    FROM household_products p
    WHERE p.quantity <= p.min_stock
      AND NOT EXISTS (
          SELECT 1
          FROM shopping_list s
          WHERE s.product_name = p.product_name
            AND s.unit = p.unit
            AND s.is_purchased = 'N'
      );

    COMMIT;

    DBMS_OUTPUT.PUT_LINE('Shopping list generated successfully!');
END;
/

BEGIN
    generate_shopping_list;
END;
