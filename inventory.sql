CREATE OR REPLACE PROCEDURE add_product (
    p_product_name IN VARCHAR2,
    p_category     IN VARCHAR2,
    p_quantity    IN NUMBER,
    p_unit        IN VARCHAR2,
    p_min_stock   IN NUMBER,
    p_expiry_date IN DATE
)
AS
BEGIN
    INSERT INTO household_products (
        product_name,
        category,
        quantity,
        unit,
        min_stock,
        purchase_date,
        expiry_date
    )
    VALUES (
        p_product_name,
        p_category,
        p_quantity,
        p_unit,
        p_min_stock,
        SYSDATE,
        p_expiry_date
    );

    COMMIT;

    DBMS_OUTPUT.PUT_LINE('Product added successfully!');
END;
