CREATE TABLE household_products (
    product_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR2(100) NOT NULL,
    category VARCHAR2(50),
    quantity NUMBER(10,2) DEFAULT 0 NOT NULL,
    unit VARCHAR2(20),
    min_stock NUMBER(10,2) DEFAULT 1 NOT NULL,
    purchase_date DATE DEFAULT SYSDATE,
    expiry_date DATE,
    CONSTRAINT chk_product_quantity CHECK (quantity >= 0),
    CONSTRAINT chk_min_stock CHECK (min_stock >= 0)
);

